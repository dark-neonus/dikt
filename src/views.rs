//! Generated views: backlog, decision review flags and daily/weekly activity reports.

use std::fs;
use std::sync::LazyLock;

use chrono::{Datelike, Duration, NaiveDate};
use regex::Regex;

use crate::bail;
use crate::error::{Error, Result};
use crate::store::{Item, Items, Store, atomic_write, parse_date, today};

pub const START: &str = "<!-- dikt:generated:start -->";
pub const END: &str = "<!-- dikt:generated:end -->";

/// Why an accepted decision needs review: due revisit date, outdated or superseded evidence.
pub fn review_reasons(item: &Item, items: &Items, today: NaiveDate) -> Vec<String> {
    if item.kind() != "decision" || item.status() != "accepted" {
        return Vec::new();
    }
    let mut reasons = Vec::new();
    let revisit = item.str("revisit");
    if !revisit.is_empty() && revisit <= today.to_string().as_str() {
        reasons.push(format!("revisit date {revisit}"));
    }
    for identifier in item.list("based_on") {
        if items
            .get(&identifier)
            .is_some_and(|evidence| evidence.status() == "outdated")
        {
            reasons.push(format!("outdated evidence {identifier}"));
        }
        let mut replacements: Vec<&str> = items
            .values()
            .filter(|candidate| {
                candidate.kind() == "knowledge"
                    && candidate.list("supersedes").contains(&identifier)
            })
            .map(Item::id)
            .collect();
        replacements.sort();
        if !replacements.is_empty() {
            reasons.push(format!(
                "superseded evidence {identifier} (by {})",
                replacements.join(", ")
            ));
        }
    }
    reasons
}

fn priority(item: &Item) -> i64 {
    item.metadata
        .get("priority")
        .and_then(|value| value.as_i64())
        .unwrap_or(4)
}

pub fn backlog_text(items: &Items, today_override: Option<NaiveDate>) -> String {
    let today = today_override.unwrap_or_else(today);
    let mut result = String::from("# Backlog\n\nGENERATED by dikt; do not edit.\n");
    let mut active: Vec<&Item> = items
        .values()
        .filter(|item| item.kind() == "task" && !matches!(item.status(), "done" | "cancelled"))
        .collect();
    active.sort_by(|a, b| {
        let due = |item: &Item| {
            if item.str("due").is_empty() {
                "9999".to_string()
            } else {
                item.str("due").to_string()
            }
        };
        (priority(a), due(a), a.id()).cmp(&(priority(b), due(b), b.id()))
    });
    let soon = (today + Duration::days(7)).to_string();
    let mut groups: Vec<(&str, Vec<&Item>)> = vec![(
        "Overdue / Due Soon",
        active
            .iter()
            .copied()
            .filter(|item| !item.str("due").is_empty() && item.str("due") <= soon.as_str())
            .collect(),
    )];
    for (label, status) in [
        ("In Progress", "in_progress"),
        ("Blocked", "blocked"),
        ("Todo", "todo"),
    ] {
        groups.push((
            label,
            active
                .iter()
                .copied()
                .filter(|item| item.status() == status)
                .collect(),
        ));
    }
    for (heading, group) in groups {
        result += &format!("\n## {heading}\n\n");
        if group.is_empty() {
            result += "None.\n";
        } else {
            for item in group {
                let due = if item.str("due").is_empty() {
                    "none"
                } else {
                    item.str("due")
                };
                result += &format!(
                    "- {} {} (P{}; due {due})\n",
                    item.id(),
                    item.str("title"),
                    priority(item)
                );
            }
        }
    }
    result += "\n## Decisions to Revisit\n\n";
    let reviews: Vec<String> = items
        .values()
        .filter_map(|item| {
            let reasons = review_reasons(item, items, today);
            (!reasons.is_empty()).then(|| {
                format!(
                    "- {} {}: {}",
                    item.id(),
                    item.str("title"),
                    reasons.join(", ")
                )
            })
        })
        .collect();
    if reviews.is_empty() {
        result += "None.\n";
    } else {
        result += &(reviews.join("\n") + "\n");
    }
    result
}

/// Log events of every item on a given day: (item, event, message).
pub fn activity(items: &Items, day: NaiveDate) -> Vec<(&Item, String, String)> {
    static ENTRY: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"^- (\d{4}-\d{2}-\d{2})T\S+ \[([a-z_]+)\] (.*)$").unwrap());
    let day = day.to_string();
    let mut result = Vec::new();
    for item in items.values() {
        for line in item.section("Log").lines() {
            if let Some(captures) = ENTRY.captures(line)
                && captures[1] == day
            {
                result.push((item, captures[2].to_string(), captures[3].to_string()));
            }
        }
    }
    result
}

pub fn daily_text(items: &Items, day: NaiveDate) -> String {
    let entries = activity(items, day);
    let mut result = String::from("## Tasks Completed\n\n");
    let completed: Vec<String> = entries
        .iter()
        .filter(|(item, event, _)| event == "closed" && item.kind() == "task")
        .map(|(item, _, message)| format!("- {} {}: {message}", item.id(), item.str("title")))
        .collect();
    result += &if completed.is_empty() {
        "None recorded.\n".into()
    } else {
        completed.join("\n") + "\n"
    };
    result += "\n## Other Activity\n\n";
    let other: Vec<String> = entries
        .iter()
        .filter(|(_, event, _)| event != "closed")
        .map(|(item, event, message)| format!("- {} [{event}] {message}", item.id()))
        .collect();
    result += &if other.is_empty() {
        "None recorded.\n".into()
    } else {
        other.join("\n") + "\n"
    };
    result
}

/// Replace only the generated block of a report, preserving handwritten text around it.
pub fn save_report(
    store: &Store,
    relative: &str,
    heading: &str,
    generated: &str,
) -> Result<String> {
    let path = store.safe_path(relative)?;
    let block = format!("{START}\n{}\n{END}", generated.trim_end());
    let text = if path.exists() {
        let text = fs::read_to_string(&path)?;
        let ordered = text.matches(START).count() == 1
            && text.matches(END).count() == 1
            && text.find(START) < text.find(END);
        if !ordered {
            bail!(
                "Refusing to overwrite report without unique ordered generation markers: {relative}"
            );
        }
        let (start, end) = (
            text.find(START).unwrap(),
            text.find(END).unwrap() + END.len(),
        );
        format!("{}{block}{}", &text[..start], &text[end..])
    } else {
        format!("# {heading}\n\n## Summary\n\n{block}\n")
    };
    atomic_write(&path, &text)?;
    Ok(relative.to_string())
}

fn daily_path(day: NaiveDate) -> String {
    format!("reports/daily/{}/{day}.md", day.year())
}

/// Save a daily report (`today`, `yesterday`, `YYYY-MM-DD`) or the ISO week report (`week`).
pub fn report(store: &Store, period: &str, anchor: Option<NaiveDate>) -> Result<String> {
    let today = today();
    let _lock = store.write_lock()?;
    let items = store.load()?;
    if period == "week" {
        let day = anchor.unwrap_or(today);
        let monday = day - Duration::days(day.weekday().num_days_from_monday() as i64);
        let week = monday.iso_week();
        let mut generated = String::new();
        for offset in 0..7 {
            let entry = monday + Duration::days(offset);
            if entry > today {
                break;
            }
            let relative = daily_path(entry);
            save_report(
                store,
                &relative,
                &format!("Daily Report: {entry}"),
                &daily_text(&items, entry),
            )?;
            let daily = fs::read_to_string(store.safe_path(&relative)?)?;
            let marker = daily.find(START).unwrap_or(daily.len());
            let summary = match daily[..marker].find("## Summary") {
                Some(position) => daily[position + "## Summary".len()..marker]
                    .trim()
                    .to_string(),
                None => String::new(),
            };
            generated += &format!("## {entry}\n\n");
            if !summary.is_empty() {
                generated += &format!("{summary}\n\n");
            }
            generated += &daily_text(&items, entry)
                .replace("## Tasks Completed", "### Tasks Completed")
                .replace("## Other Activity", "### Other Activity");
            generated += "\n";
        }
        let label = format!("{}-W{:02}", week.year(), week.week());
        return save_report(
            store,
            &format!("reports/weekly/{}/{label}.md", week.year()),
            &format!("Weekly Report: {label}"),
            &generated,
        );
    }
    if anchor.is_some() {
        bail!("--date is only used with report week");
    }
    let day = match period {
        "today" => today,
        "yesterday" => today - Duration::days(1),
        other => {
            parse_date(other).map_err(|_| Error::new("Use today, yesterday, YYYY-MM-DD or week"))?
        }
    };
    save_report(
        store,
        &daily_path(day),
        &format!("Daily Report: {day}"),
        &daily_text(&items, day),
    )
}
